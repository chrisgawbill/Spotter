import assert from 'node:assert/strict';
import { test } from 'node:test';
import { mkdtemp, mkdir, writeFile, rm, readdir } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { chromium } from 'playwright';
import { createDashboardServer } from '../src/dashboard.mjs';
import { spotterRoot } from '../src/paths.mjs';

test('dashboard starts real runs, updates activity, and embeds reports with screenshots', async () => {
  const root = await mkdtemp(path.join(tmpdir(), 'spotter-dashboard-browser-'));
  const repo = path.join(root, 'repo');
  const configFile = path.join(spotterRoot, 'projects/dashboard-demo.yml');
  await mkdir(repo);
  const git = (...args) => execFileSync('git', ['-C', repo, ...args], { stdio: 'pipe' });
  git('init', '-b', 'main');
  git('config', 'user.email', 'qa@example.test');
  git('config', 'user.name', 'QA');
  await writeFile(path.join(repo, 'index.html'), '<h1>Healthy demo</h1>');
  git('add', '.'); git('commit', '-m', 'Healthy baseline');
  git('switch', '-c', 'seeded');
  await writeFile(path.join(repo, 'index.html'), '<h1>Seeded demo</h1><script>throw new Error("seeded dashboard failure")</script>');
  git('add', '.'); git('commit', '-m', 'Seed browser failure');
  git('switch', 'main');
  await writeFile(configFile, JSON.stringify({ repo, baseBranch: 'main', checks: [{ name: 'slow-check', run: 'node -e "setTimeout(() => {}, 2500)"' }], web: { build: { run: 'mkdir -p dist && cp index.html dist/' }, routes: ['/'], viewports: [375], colorSchemes: ['light'], accessibility: false, keyboard: false, faultInjection: false, settleMs: 100 } }));
  const server = createDashboardServer({ projectsRoot: root, branchRefreshMs: 0, home: path.join(root, 'data'), projectNames: async () => (await readdir(path.join(spotterRoot, 'projects'))).filter((file) => /^dashboard-.*\.yml$/.test(file)).map((file) => file.slice(0, -4)) });
  await new Promise((resolve) => server.listen(0, '127.0.0.1', resolve));
  const origin = `http://127.0.0.1:${server.address().port}`;
  const browser = await chromium.launch();
  try {
    const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
    const errors = [];
    page.on('pageerror', (error) => errors.push(error.message));
    await page.goto(origin);
    await page.selectOption('#project', 'dashboard-demo');
    await page.selectOption('#branch', 'main');
    await page.click('#submit');
    await page.waitForFunction(() => document.querySelector('#identity').textContent.includes('dashboard-demo / main'));
    await page.waitForFunction(() => document.querySelector('#current').textContent.includes('slow-check'));
    assert.match(await page.textContent('#status'), /RUNNING/);
    await page.waitForFunction(() => document.querySelector('#status').textContent.includes('PASS'), { timeout: 30000 });
    await page.frameLocator('#report').getByRole('heading', { name: 'Spotter: dashboard-demo' }).waitFor();
    const first = page.url();
    await page.getByRole('link', { name: 'Configurations', exact: true }).click();
    await page.waitForSelector('#config-page:not([hidden])');
    await page.locator('[data-config="dashboard-demo"]').click();
    await page.waitForFunction(() => document.querySelector('#field-repo').value.length > 0);
    await page.locator('#field-workdir').focus();
    assert.match(await page.textContent('#field-suggestion'), /repository root/);
    await page.selectOption('#field-reference', 'web.routes');
    assert.match(await page.textContent('#field-suggestion'), /hash-based/);
    await page.locator('#field-install').fill('');
    await page.click('#save-config');
    await page.waitForFunction(() => document.querySelector('#config-message').textContent === 'Configuration saved.');
    await page.setViewportSize({ width: 375, height: 812 });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await page.screenshot({ path: '/tmp/spotter-config-mobile.png', fullPage: true });
    await page.setViewportSize({ width: 1280, height: 900 });
    await page.evaluate(() => scrollTo(0, 0));
    await page.screenshot({ path: '/tmp/spotter-config-desktop.png', fullPage: true });
    await page.click('#close-config');
    await writeFile(path.join(repo, 'package.json'), JSON.stringify({ scripts: { test: 'node --test', build: 'vite build' }, devDependencies: { vite: '*' } }));
    await writeFile(path.join(repo, 'routes.tsx'), `import { HashRouter, Route } from 'react-router-dom'; export const Routes = () => <HashRouter><Route path="/" /><Route path="reports" /><Route path="team/:id" /></HashRouter>`);
    await writeFile(path.join(repo, 'vite.config.ts'), `export default { base: '/demo/' };`);
    await page.click('#setup-project');
    await page.locator('[data-folder]').filter({ hasText: 'repo →' }).click();
    await page.waitForFunction((folder) => document.querySelector('#folder-path').textContent === folder, repo);
    await page.click('#detect-project');
    await page.waitForFunction(() => document.querySelector('#config-name').value === 'repo' && document.activeElement.id === 'config-name');
    assert.match(await page.inputValue('#config-source'), /outDir: dist/);
    assert.match(await page.inputValue('#config-source'), /#\/reports/);
    assert.match(await page.inputValue('#config-source'), /base: \/demo\//);
    assert.match(await page.textContent('#config-message'), /team\/:id/);
    assert.match(await page.textContent('#config-message'), /Review generated commands/);
    page.once('dialog', (dialog) => dialog.accept());
    await page.click('#close-config');
    await page.click('#new-config');
    await page.waitForFunction(() => document.activeElement.id === 'config-name' && document.querySelector('#config-name').value === '');
    await page.locator('#config-name').fill('dashboard-created');
    await page.locator('#field-repo').fill(repo);
    await page.locator('#field-install').fill('');
    await page.click('#apply-fields');
    await page.waitForFunction(() => document.querySelector('#config-message').textContent.startsWith('Basic fields applied.'));
    await page.locator('#config-source').fill(`repo: ${repo}\nweb:\n  build:\n    run: npm run build\n  routes: [/home]`);
    await page.locator('#config-source').press('Control+End');
    await page.waitForFunction(() => document.querySelector('#field-reference').value === 'web.routes');
    await page.click('#save-config');
    await page.waitForFunction(() => document.querySelector('#config-message').textContent === 'Configuration saved.');
    await page.locator('[data-config="dashboard-created"]').waitFor();
    await page.click('#close-config');
    await page.locator('[data-config="dashboard-created"]').click();
    await page.waitForFunction(() => document.querySelector('#editor-title').textContent === 'Edit dashboard-created');
    page.once('dialog', (dialog) => dialog.accept());
    await page.click('#delete-config');
    await page.waitForSelector('#config-editor[hidden]', { state: 'attached' });
    await page.waitForSelector('[data-config="dashboard-created"]', { state: 'detached' });
    await page.getByRole('link', { name: 'Runs', exact: true }).click();
    await page.waitForSelector('#run-page:not([hidden])');
    await page.screenshot({ path: '/tmp/spotter-dashboard-desktop.png', fullPage: true });
    await page.selectOption('#branch', 'seeded');
    await page.click('#submit');
    await page.waitForFunction((before) => location.href !== before, first);
    await page.waitForFunction(() => document.querySelector('#status').textContent.includes('FAIL'), { timeout: 30000 });
    await page.frameLocator('#report').getByRole('heading', { name: /uncaught Error: seeded dashboard failure/ }).waitFor();
    const image = page.frameLocator('#report').getByAltText('Screenshot');
    await image.waitFor();
    assert.ok(await image.evaluate((img) => img.complete && img.naturalWidth > 0));
    await page.frameLocator('#report').locator('summary').first().click();
    await page.frameLocator('#report').getByAltText('Diff').waitFor();
    const runPath = decodeURIComponent(new URL(page.url()).hash.slice(5));
    const run = await (await fetch(`${origin}/api/runs/${runPath}`)).json();
    assert.ok(run.events.some((event) => event.activity.startsWith('browser:') && event.state === 'done'));
    assert.ok(run.report);
    await page.reload();
    await page.waitForFunction(() => document.querySelector('#status').textContent.includes('FAIL'));
    await page.frameLocator('#report').getByRole('heading', { name: /uncaught Error: seeded dashboard failure/ }).waitFor();
    await page.setViewportSize({ width: 375, height: 812 });
    await page.screenshot({ path: '/tmp/spotter-dashboard-mobile.png', fullPage: true });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    assert.deepEqual(errors, []);
    const result = { origin, events: run.events.length, status: run.status, report: run.report, screenshots: ['/tmp/spotter-dashboard-desktop.png', '/tmp/spotter-dashboard-mobile.png'] };
    console.log(JSON.stringify(result));
    await writeFile('/tmp/spotter-dashboard-evidence.json', JSON.stringify(result, null, 2));
  } finally {
    await browser.close();
    server.closeAllConnections();
    await new Promise((resolve) => server.close(resolve));
    await rm(configFile, { force: true });
    await rm(path.join(spotterRoot, 'projects/dashboard-created.yml'), { force: true });
    await rm(root, { recursive: true, force: true });
  }
});
